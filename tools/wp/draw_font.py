# ---- Font 2: symbols. Named; positions assigned in order from 0x01. Rows as above (cell rows 3..13) unless FULL.
S = {}
def s(name, rows, full=False):
    rows = [r.ljust(8 if full else 7, '.')[:8 if full else 7] for r in rows.strip('\n').split('\n')]
    n = 16 if full else 11
    while len(rows) < n: rows.append('.' * (8 if full else 7))
    assert len(rows) == n, (name, len(rows))
    S[name] = (rows, full)

