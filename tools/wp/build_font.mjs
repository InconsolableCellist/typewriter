// Builds src/wp/font/font8x16.js from tools/wp/font8x16.txt (the drawing is the source of truth).
//   node tools/wp/build_font.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const lines = readFileSync(join(root, 'tools/wp/font8x16.txt'), 'utf8').split('\n');
const font = new Uint8Array(2 * 256 * 16);   // font 1 then font 2; one byte per dot row, bit 7 the leftmost dot
const symbols = {};
for (let i = 0; i < lines.length; i++) {
  const m = /^font([12]) ([0-9a-f]{2}) (.+)$/.exec(lines[i]);
  if (!m) continue;
  const [, f, hex, name] = m, code = parseInt(hex, 16);
  for (let r = 0; r < 16; r++) {
    const row = lines[i + 1 + r];
    if (!/^[.#]{8}$/.test(row)) throw new Error(`line ${i + 2 + r}: expected 8 dots, got '${row}'`);
    let b = 0;
    for (let c = 0; c < 8; c++) if (row[c] === '#') b |= 0x80 >> c;
    font[(f === '1' ? 0 : 256 * 16) + code * 16 + r] = b;
  }
  if (f === '2') symbols[name] = code;
  i += 16;
}
const b64 = Buffer.from(font).toString('base64');
const out = `// Generated by tools/wp/build_font.mjs from tools/wp/font8x16.txt. Do not edit.
// Two fonts of 256 glyphs, 8 x 16 dots: font 1 is text at Latin-1 positions, font 2 the symbols named in SYMBOLS.
// One byte per dot row, bit 7 the leftmost dot; glyph g of font f starts at ((f - 1) * 256 + g) * 16.
const B64 = '${b64}';
const decode = (s) => (typeof atob === 'function' ? Uint8Array.from(atob(s), (c) => c.charCodeAt(0)) : new Uint8Array(Buffer.from(s, 'base64')));
export const FONT8X16 = decode(B64);
export const SYMBOLS = Object.freeze(${JSON.stringify(symbols)});
`;
mkdirSync(join(root, 'src/wp/font'), { recursive: true });
writeFileSync(join(root, 'src/wp/font/font8x16.js'), out);
console.log(`src/wp/font/font8x16.js: ${Object.keys(symbols).length} symbols, ${out.length} bytes`);
