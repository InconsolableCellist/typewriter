#!/usr/bin/env node
// Chooses the printwheel printer's missing numbers (docs/displaywriter/architecture.md 6.6) by running the headless
// mechanism, and writes them to src/machine/wp-printer-cal.js. Run: node tools/wp/calibrate_printer.mjs
//   1. Force groups and hammer energies from the face tables; on-time per group for the impact speed; the flight
//      time that results is the servo's target.
//   2. Selection peak torque so that a 24-step move, its settle and a medium flight take 15.0 ms, with the braking
//      curve tuned at each torque; then the seat time of every move length.
//   3. The carrier's lag behind its encoder at print speed, which the fire timing allows for, and how late an
//      impact can come after its planned time, which the planner allows for.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import wordproc1980 from '../../src/machine/wordproc1980.js';
import { loadGlyphs } from '../../src/machine/glyphs.js';
import { Bench, forceGroups, calibrateHammer, tuneBrakeCurve, seatTime, escapementTiming } from '../../src/sim/wp/calibrate.js';

const TARGET_24 = 0.015;          // s: 24-step move, settle and medium flight (6.6 item 1)

export async function calibrate(log = () => {}) {
  const machine = structuredClone(wordproc1980);
  const glyphs = await loadGlyphs('glyphs_wp');
  const bench = new Bench(machine, glyphs);
  const cal = machine.printer.calibration;

  cal.petalGroups = forceGroups(machine.printer, glyphs);
  const hammer = calibrateHammer(bench, cal.petalGroups);
  cal.groups = hammer.map(({ energy, speed, current, tOn, flightTarget, tPeak, dTonDFlight }) => ({ energy, speed, current, tOn, flightTarget, tPeak, dTonDFlight }));
  cal.hammerClear = Math.max(...hammer.map((h) => h.clear));
  hammer.forEach((h, g) => log(`group ${g}: ${(h.energy * 1e3).toFixed(2)} mJ, ${h.speed.toFixed(3)} m/s, on ${(h.tOn * 1e3).toFixed(3)} ms, flight ${(h.flightTarget * 1e3).toFixed(3)} ms, smallest face ${(h.smallestPressure / 1e6).toFixed(0)} MPa`));

  const flight = cal.groups[1].flightTarget;
  const at = (T) => {
    bench.sim.setParam('printer.selection.peakTorque', T);
    tuneBrakeCurve(bench);
    return seatTime(bench, 24) + flight;
  };
  let lo = 0.05, hi = 1.0;
  for (let i = 0; i < 16; i++) { const mid = 0.5 * (lo + hi); if (at(mid) > TARGET_24) lo = mid; else hi = mid; }
  cal.peakTorque = round(hi, 4);
  log(`selection peak torque ${cal.peakTorque} N m: 24 steps + settle + flight ${(at(cal.peakTorque) * 1e3).toFixed(2)} ms`);
  cal.moveTime = Array.from({ length: 49 }, (_, n) => (n ? seatTime(bench, n) : 0));
  log(`move times (ms) ${cal.moveTime.map((t) => (t * 1e3).toFixed(1)).join(' ')}`);

  cal.carrierLag = 0; cal.impactLag = 0;
  for (let i = 0; i < 3; i++) {
    const e = escapementTiming(bench);
    cal.carrierLag -= e.error; cal.impactLag = Math.max(cal.impactLag, e.lag);
  }
  const e = escapementTiming(bench);
  log(`carrier lag ${cal.carrierLag.toFixed(3)} steps, residual ${e.error.toFixed(3)} steps; impacts up to ${(cal.impactLag * 1e3).toFixed(3)} ms after plan`);
  return cal;
}

const round = (x, d) => Math.round(x * 10 ** d) / 10 ** d;
const fmt = (x) => (Array.isArray(x) ? `[${x.map(fmt).join(', ')}]` : typeof x === 'number' ? String(round(x, 9)) : `{ ${Object.entries(x).map(([k, v]) => `${k}: ${fmt(v)}`).join(', ')} }`);

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const cal = await calibrate(console.log);
  const body = Object.entries(cal).map(([k, v]) => `  ${k}: ${fmt(v)},`).join('\n');
  const out = `// Generated by tools/wp/calibrate_printer.mjs (architecture.md 6.6). Do not edit by hand: change the
// printer's parameters in wordproc1980.js and run the tool again.
export default {
${body}
};
`;
  await writeFile(new URL('../../src/machine/wp-printer-cal.js', import.meta.url), out);
  console.log('wrote src/machine/wp-printer-cal.js');
}
