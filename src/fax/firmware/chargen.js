const UNKNOWN = [0x7f, 0x41, 0x41, 0x41, 0x7f];

/** The glyph's columns; characters outside the set print as a hollow box. */
export function glyph(ch) { return FONT[ch] ?? UNKNOWN; }
export const hasGlyph = (ch) => ch in FONT;

/** Is dot (col 0..4, row 0..6) of `ch` set? */
export const dot = (ch, col, row) => (glyph(ch)[col] >> row) & 1;

/** Character metrics in head dots at a scale (sx, sy dots per matrix dot). */
export const metrics = (sx = 3, sy = 3) => ({ w: 5 * sx, h: 7 * sy, pitch: 6 * sx, line: 11 * sy });

/** Default report cell: 18 dots wide, 33 lines a text line. */
export const CELL = metrics(3, 3);
export const COLUMNS = Math.floor(WIDTH / CELL.pitch);

/** A packed bilevel raster of `height` rows, 1728 pels wide. */
export class Raster {
  constructor(height, width = WIDTH) {
    this.width = width;
    this.stride = (width + 7) >>> 3;
    this.height = height;
    this.data = new Uint8Array(this.stride * height);
  }

  set(x, y) {
    if (x < 0 || y < 0 || x >= this.width || y >= this.height) return;
    this.data[y * this.stride + (x >>> 3)] |= 0x80 >>> (x & 7);
  }

  get(x, y) {
    if (x < 0 || y < 0 || x >= this.width || y >= this.height) return 0;
    return (this.data[y * this.stride + (x >>> 3)] >>> (7 - (x & 7))) & 1;
  }

  fill(x0, y0, w, h) { for (let y = y0; y < y0 + h; y++) for (let x = x0; x < x0 + w; x++) this.set(x, y); }
  hline(x0, y, w, thick = 2) { this.fill(x0, y, w, thick); }
  vline(x, y0, h, thick = 2) { this.fill(x, y0, thick, h); }
  frame(x0, y0, w, h, thick = 2) { this.hline(x0, y0, w, thick); this.hline(x0, y0 + h - thick, w, thick); this.vline(x0, y0, h, thick); this.vline(x0 + w - thick, y0, h, thick); }

  /** Draw text with its top-left at (x, y); returns the x after the last character. */
  text(x, y, str, { sx = 3, sy = 3, bold = false } = {}) {
    const m = metrics(sx, sy);
    for (const ch of String(str)) {
      const cols = glyph(ch);
      for (let c = 0; c < 5; c++) for (let r = 0; r < 7; r++) {
        if (!((cols[c] >> r) & 1)) continue;
        this.fill(x + c * sx, y + r * sy, sx + (bold ? 1 : 0), sy);
      }
      x += m.pitch;
    }
    return x;
  }

  /** Text at a character column and text line of the report grid, after a left margin. */
  cell(col, line, str, opts = {}) {
    return this.text(MARGIN + col * CELL.pitch, line * CELL.line + (opts.dy ?? 0), str, opts);
  }

  /** Row y as a fresh packed line. */
  row(y) { return this.data.slice(y * this.stride, (y + 1) * this.stride); }

  /** Black pels in the whole raster (for tests). */
  get ink() { let n = 0; for (const b of this.data) { let v = b; while (v) { n += v & 1; v >>>= 1; } } return n; }

  /** The raster cropped or extended to `rows` rows. */
  resize(rows) {
    const r = new Raster(rows, this.width);
    r.data.set(this.data.subarray(0, Math.min(this.data.length, r.data.length)));
    return r;
  }
}

/** The left margin of reports, in dots: 4 mm [A]. */
export const MARGIN = 32;

/** Render lines of text as a raster on the report grid (one text line = CELL.line rows). */
export function renderText(lines, { top = 1, bottom = 2, sx = 3, sy = 3 } = {}) {
  const m = metrics(sx, sy);
  const r = new Raster((lines.length + top + bottom) * m.line);
  lines.forEach((s, i) => r.text(MARGIN, (i + top) * m.line, s, { sx, sy }));
  return r;
}
