// The machine's character generator for printed output (reports, lists and the header line on sent pages), and a
// small raster to draw into. Our own 5 x 7 dot matrix in the common manner of the period's LCD and dot printers,
// enlarged for the thermal head: the head has 8 dots/mm across [S] and reports are printed at fine resolution, 7.7
// lines/mm [A], so one matrix dot is drawn 3 dots wide and 3 lines high and a character is about 1.9 x 2.7 mm, on an
// 18-dot pitch (96 columns across 1728 dots). How Sharp's own report font looks is not known [A].
//
// Bitmaps are packed rows, 1728 pels, the first pel in the most significant bit, 1 = black: what src/fax/t4/ codes
// and what the printer interface takes (devices.md).

